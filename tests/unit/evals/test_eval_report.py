"""T-40: `make eval` gates every suite against thresholds and the committed baseline."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

import pytest
from evalgate.models import CaseResult, MetricResult, Report

from collections_copilot.evals import report as er


def _report(value: float, *, suite: str = "replies", n: int = 50) -> Report:
    hits = round(value * n)
    return Report(
        suite=suite,
        run_id="r",
        created_at=datetime(2026, 3, 10, tzinfo=UTC),
        n_cases=n,
        metrics={
            "acc": MetricResult(value=value, threshold=0.8, direction="higher", passed=value >= 0.8)
        },
        cases=[
            CaseResult(
                id=f"c{i}", split="test", scores={"acc": 1.0 if i < hits else 0.0}, passed=True
            )
            for i in range(n)
        ],
    )


def test_baseline_roundtrip_and_regression_gate(tmp_path: Path) -> None:
    path = tmp_path / "baseline.json"
    er.write_baselines(path, {"replies": _report(0.96)})
    base = er.load_baselines(path)
    assert set(base) == {"replies"}
    assert base["replies"].metrics["acc"].value == 0.96

    same = er.gate(_report(0.96), base["replies"], None)
    assert same.passed
    # 0.96 -> 0.86: still above the 0.8 threshold, but 10 pp worse than the baseline.
    worse = er.gate(_report(0.86), base["replies"], None)
    assert not worse.passed
    assert [f.reason for f in worse.failures] == ["regression"]
    below = er.gate(_report(0.70), None, None)
    assert [f.reason for f in below.failures] == ["threshold"]
    assert er.load_baselines(tmp_path / "missing.json") == {}


def test_report_states_mode_models_and_live_status() -> None:
    rep = _report(0.96)
    rep.mode = "offline"
    rep.models = ["fake"]
    rep.prompt_hashes = {"classify_reply": "a" * 64}
    rep.extensions = {"split": "test", "provider": "fake"}
    run = er.SuiteRun(name="replies", report=rep, check=er.gate(rep, None, None), dev=_report(0.97))
    md = er.render([run], live_section=None)
    assert md.startswith("# Evaluation report")
    assert "Generated by `scripts/eval_report.py`" in md
    assert "mode **offline**" in md
    assert "Live evals were not run" in md
    assert "`classify_reply` aaaaaaaaaaaa" in md
    assert "Dev split (informational" in md
    assert "| `replies` | test | 50 | PASS |" in md


def test_offline_models_never_claim_a_real_model() -> None:
    from collections_copilot.config import Settings

    assert er.models_for(Settings(llm_provider="fake")) == ["fake"]
    live = er.models_for(Settings(llm_provider="anthropic"))
    assert live == sorted({Settings().model_fast, Settings().model_reasoning})


async def test_errored_runs_never_become_the_baseline(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(er, "BASELINE", tmp_path / "baseline.json")
    monkeypatch.setattr(er, "REPORTS_DIR", tmp_path)
    errored = _report(0.96)
    errored.cases[0].error = "TimeoutError: "

    async def fake_run_one(name: str, split: str, mode: str, settings: object) -> Report:
        return errored

    monkeypatch.setattr(er, "run_one", fake_run_one)
    runs, created = await er.run_all(
        ["replies"], mode="offline", with_dev=False, update_baseline=False
    )
    assert not created
    assert not (tmp_path / "baseline.json").exists()
    assert not runs[0].check.passed

    errored.cases[0].error = None
    errored.metrics["acc"].passed = False  # below threshold, but every case ran
    runs, created = await er.run_all(
        ["replies"], mode="offline", with_dev=False, update_baseline=False
    )
    assert created
    assert (tmp_path / "baseline.json").exists()
    assert not runs[0].check.passed


async def test_tone_rubric_loads_and_offline_calibration_is_reported() -> None:
    from evalgate.loader import load_rubric

    from collections_copilot.evals import judge

    rubric = load_rubric(judge.RUBRIC)
    assert rubric.route == "judge_tone"
    assert rubric.thresholds.agreement_min == 0.8
    result = await judge.calibrate_tone("test")
    assert result.n == 40
    assert 0.0 <= result.agreement <= 1.0
    section = er.tone_section(result, mode="offline")
    assert "informational" in section
    assert f"{result.agreement:.4f}" in section
