"""make docs: generated reference documentation.

Writes infra/terraform/modules/<module>/README.md and envs/dev/README.md from the Terraform code
with terraform-docs (inputs, outputs, resources). `--check` writes nothing and exits 1 when a
README differs from what the code would generate. OpenAPI, the frontend types and the
screenshots are regenerated by the other steps of `make docs`.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "<!-- Generated by scripts/gen_docs.py (make docs) from the Terraform code; do not edit. -->\n\n"


def terraform_docs(directory: Path) -> str:
    out = subprocess.run(
        ["terraform-docs", "markdown", "table", "--hide", "providers", str(directory)],
        capture_output=True,
        text=True,
        check=True,
    )
    return out.stdout


def targets(root: Path) -> list[Path]:
    dirs = sorted(p.parent for p in root.glob("modules/*/main.tf"))
    dirs += [p for p in [root / "envs" / "dev"] if (p / "main.tf").is_file()]
    return dirs


def main(argv: list[str] | None = None, render: Callable[[Path], str] = terraform_docs) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT / "infra" / "terraform")
    parser.add_argument("--check", action="store_true", help="fail if a README is out of date")
    args = parser.parse_args(argv)
    stale = []
    for directory in targets(args.root):
        title = f"# {directory.relative_to(args.root)}\n\n"
        body = HEADER + title + render(directory).strip() + "\n"
        readme = directory / "README.md"
        if readme.is_file() and readme.read_text() == body:
            continue
        stale.append(readme)
        if not args.check:
            readme.write_text(body)
    for readme in stale:
        print(f"{'stale' if args.check else 'wrote'} {readme}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
