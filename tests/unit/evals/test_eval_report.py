async def test_replayed_cassettes_are_labelled_not_reported_as_fake() -> None:
    from collections_copilot.llm.providers.base import ProviderRequest, ProviderResponse

    class Recorded:
        name = "fake"

        def __init__(self, model: str) -> None:
            self.model = model

        async def complete(self, request: ProviderRequest) -> ProviderResponse:
            return ProviderResponse("{}", "end_turn", self.model)

    counter = er.ReplayCounter()
    request = ProviderRequest("classify_reply", "claude-haiku-5-5", "s", "u", {}, "low", 64)
    await counter.wrap(Recorded("claude-haiku-5-5")).complete(request)
    await counter.wrap(Recorded("fake")).complete(request)
    assert counter.calls == 2
    assert dict(counter.replayed) == {"claude-haiku-5-5": 1}
    rep = _report(0.96)
    er.label_models(rep, counter)
    assert rep.models == ["claude-haiku-5-5", "fake"]
    assert rep.extensions["replayed_calls"] == 1
    run = er.SuiteRun(name="replies", report=rep, check=er.gate(rep, None, None))
    md = er.render([run], live_section=None)
    assert "replayed recorded live responses for 1 of 2 model calls" in md


def test_report_layout_and_live_wording() -> None:
    rep = _report(0.96)
    run = er.SuiteRun(name="replies", report=rep, check=er.gate(rep, None, None), dev=_report(0.97))
    lines = er.render([run], live_section=None).splitlines()
    dev = lines.index("## Dev split (informational, the tuning split, mode offline)")
    assert lines[dev - 1] == ""  # markdownlint MD022
    assert any("No live run is recorded" in line for line in lines)


